#!/bin/bash

# Развертывание исправлений тепловой карты и производительности
SERVER="217.114.1.117"
USER="root"
REMOTE_PATH="/opt/inventory_system"

echo "🔧 ИСПРАВЛЕНИЕ ТЕПЛОВОЙ КАРТЫ И ПРОИЗВОДИТЕЛЬНОСТИ"
echo "📅 Время: $(date)"
echo ""

# Создаем резервную копию
echo "💾 Создание резервной копии..."

ssh "$USER@$SERVER" "
    cd $REMOTE_PATH
    
    if [ -f webhook_persistent_app.py ]; then
        cp webhook_persistent_app.py webhook_persistent_app_backup_perf_$(date +%Y%m%d_%H%M%S).py
        echo '✅ Резервная копия создана'
    fi
"

# Загружаем исправленное приложение
echo "📤 Загрузка исправленного приложения..."

scp webhook_app_enhanced_analytics.py "$USER@$SERVER:$REMOTE_PATH/webhook_persistent_app.py" || {
    echo "❌ Ошибка загрузки"
    exit 1
}

echo "✅ Файл загружен"

# Перезапускаем сервис
echo ""
echo "🔄 Перезапуск аналитического сервиса..."

ssh "$USER@$SERVER" "
    cd $REMOTE_PATH
    
    echo '🔄 Остановка сервиса...'
    systemctl stop webhook-analytics
    
    echo '🚀 Запуск обновленного сервиса...'
    systemctl start webhook-analytics
    
    sleep 5
    
    echo '📊 Проверка статуса...'
    systemctl status webhook-analytics --no-pager | head -10
"

# Проверка результата
echo ""
echo "🔍 Проверка исправлений..."

sleep 10

curl -s -o /dev/null -w "%{http_code}" "http://$SERVER:8502" | grep -q "200" && {
    echo "✅ Приложение с исправлениями доступно!"
    echo ""
    echo "🌐 Откройте: http://$SERVER:8502"
    echo ""
    echo "🔧 КРИТИЧЕСКИЕ ИСПРАВЛЕНИЯ:"
    echo "   ✅ Тепловая карта показывает только реальные даты"
    echo "   ✅ Убраны несуществующие дни (например, 31 февраля)"
    echo "   ✅ Добавлено ограничение на количество данных (50k записей)"
    echo "   ✅ Альтернативная календарная визуализация"
    echo "   ✅ Предупреждения о больших объемах данных"
    echo "   ✅ Оптимизация для анализа 180+ дней"
    echo "   ✅ Показ статистики вместо тяжелых графиков при >50k записей"
    echo ""
    echo "📊 НОВЫЕ ВОЗМОЖНОСТИ:"
    echo "   📅 Календарный вид продаж (scatter plot)"
    echo "   📈 Статистика по дням (лучший день, средняя выручка)"
    echo "   ⚡ Умное ограничение визуализаций для производительности"
} || {
    echo "⚠️  Сервис еще запускается или есть проблемы"
    echo "🔍 Проверьте логи на сервере"
}

echo ""
echo "✅ РАЗВЕРТЫВАНИЕ ИСПРАВЛЕНИЙ ЗАВЕРШЕНО!"
echo ""
echo "💡 РЕКОМЕНДАЦИИ:"
echo "   - Для больших объемов данных используйте периоды 30-90 дней"
echo "   - Тепловая карта автоматически скрывается при >50k записей"
echo "   - При анализе 'Весь период' некоторые графики упрощены для скорости"