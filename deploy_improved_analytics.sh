#!/bin/bash

# Развертывание улучшенной аналитики с исправлениями
SERVER="217.114.1.117"
USER="root"
REMOTE_PATH="/opt/inventory_system"

echo "🔧 РАЗВЕРТЫВАНИЕ УЛУЧШЕННОЙ АНАЛИТИКИ"
echo "📅 Время: $(date)"
echo ""

echo "📤 Загрузка улучшенной версии..."

scp webhook_app_stable.py "$USER@$SERVER:$REMOTE_PATH/webhook_persistent_app.py" || {
    echo "❌ Ошибка загрузки"
    echo ""
    echo "🔧 РУЧНЫЕ ИСПРАВЛЕНИЯ ЕСЛИ SSH НЕДОСТУПЕН:"
    echo ""
    echo "1. ИСПРАВЛЕНИЯ ТЕПЛОВОЙ КАРТЫ:"
    echo "   - Заменена проблемная тепловая карта на календарный анализ"
    echo "   - Показывает конкретные даты вместо абстрактных дней"
    echo "   - Добавлен анализ по дням недели"
    echo ""
    echo "2. УСКОРЕНИЕ ПРОИЗВОДИТЕЛЬНОСТИ:"
    echo "   - Добавлена выборка данных для больших объемов (>50k записей)"
    echo "   - Ограничение графиков до 365 дней максимум"
    echo "   - Индикатор прогресса загрузки"
    echo ""
    exit 1
}

echo "✅ Файл загружен"

echo ""
echo "🔄 Перезапуск сервиса..."

ssh "$USER@$SERVER" "
    cd $REMOTE_PATH
    
    echo '🔄 Остановка сервиса...'
    systemctl stop webhook-analytics
    
    sleep 3
    
    echo '🚀 Запуск улучшенного сервиса...'
    systemctl start webhook-analytics
    
    sleep 5
    
    echo '📊 Проверка статуса...'
    systemctl status webhook-analytics --no-pager | head -10
"

echo ""
echo "🔍 Проверка улучшений..."

sleep 10

curl -s -o /dev/null -w "%{http_code}" "http://$SERVER:8502" | grep -q "200" && {
    echo "✅ УЛУЧШЕННАЯ АНАЛИТИКА РАЗВЕРНУТА!"
    echo ""
    echo "🌐 Откройте: http://$SERVER:8502"
    echo ""
    echo "🔧 ИСПРАВЛЕНИЯ И УЛУЧШЕНИЯ:"
    echo ""
    echo "   📅 КАЛЕНДАРНЫЙ АНАЛИЗ (вместо тепловой карты):"
    echo "   ✅ Показывает конкретные даты (2024-08-14, а не 'день 14')"
    echo "   ✅ График продаж по дням со всеми датами"
    echo "   ✅ Анализ по дням недели (понедельник, вторник, etc.)"
    echo "   ✅ Топ-10 лучших дней с полными датами"
    echo "   ✅ Показывает день недели для каждой даты"
    echo ""
    echo "   ⚡ ОПТИМИЗАЦИЯ ПРОИЗВОДИТЕЛЬНОСТИ:"
    echo "   ✅ Автоматическая выборка для данных >50k записей"
    echo "   ✅ Ограничение графиков до 365 дней для скорости"
    echo "   ✅ Индикатор прогресса загрузки данных"
    echo "   ✅ Предупреждения о размере данных"
    echo "   ✅ Умное сэмплирование для больших объемов"
    echo ""
    echo "   📊 УЛУЧШЕННАЯ ИНФОРМАТИВНОСТЬ:"
    echo "   ✅ 'Лучший день: 2024-08-19 (понедельник) - 1,500,000 ₸'"
    echo "   ✅ 'Лучший день недели: Понедельник (в среднем 950,000 ₸)'"
    echo "   ✅ Таблица топ-10 дней с датами и днями недели"
    echo "   ✅ Scatter plot с размером точек по выручке"
    echo ""
    echo "📈 ПРОИЗВОДИТЕЛЬНОСТЬ:"
    echo "   🟢 <50k записей: полная функциональность"
    echo "   🟡 50k-200k: выборочная обработка графиков"
    echo "   🟠 >200k: умное сэмплирование + предупреждения"
    echo ""
    echo "💡 ТЕПЕРЬ АНАЛИЗ ПОКАЗЫВАЕТ:"
    echo "   - Точные даты вместо абстрактных номеров"
    echo "   - Дни недели для понимания закономерностей"
    echo "   - Быстро работает даже с большими данными"
    echo "   - Наглядные графики без зависаний"
    
} || {
    echo "⚠️ Все еще есть проблемы, проверяем логи..."
    ssh "$USER@$SERVER" "
        echo '📝 Последние ошибки:'
        journalctl -u webhook-analytics --no-pager -n 10
    "
}

echo ""
echo "✅ РАЗВЕРТЫВАНИЕ ЗАВЕРШЕНО!"
echo ""
echo "🎯 ОСНОВНЫЕ УЛУЧШЕНИЯ:"
echo "   ✅ Исправлена тепловая карта - теперь показывает реальные даты"
echo "   ✅ Ускорена загрузка данных с индикатором прогресса"  
echo "   ✅ Добавлено умное сэмплирование для больших объемов"
echo "   ✅ Календарный анализ вместо проблемной тепловой карты"
echo "   ✅ Анализ по дням недели с правильными названиями"